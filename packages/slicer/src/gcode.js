// G-code: a writer for the built-in slicer and a tolerant parser/analyser that also reads G-code from
// PrusaSlicer, OrcaSlicer/Bambu Studio and Cura (feature types come from their ;TYPE: comments).

import { resolveProfile } from './profile.js';
import { sliceLayers, planLayer } from './slice.js';

export const TYPE_LABEL = Object.freeze({ outer: 'Outer wall', inner: 'Inner wall', solid: 'Solid infill', sparse: 'Sparse infill', top: 'Top surface', bottom: 'Bottom surface', gap: 'Gap fill', bridge: 'Bridge', support: 'Support', skirt: 'Skirt', other: 'Other' });

/** Cross-section of the extruded line: a rectangle with semicircular ends (the usual slicer model). */
export const lineArea = (w, h) => (w - h) * h + (Math.PI * h * h) / 4;
export const widthFromArea = (a, h) => a / h + h * (1 - Math.PI / 4);
const filArea = d => Math.PI * (d / 2) ** 2;
const f = (x, n = 3) => +x.toFixed(n);

/** Normalise a slicer's ;TYPE: label to one of TYPE_LABEL's keys. */
export function normalizeType(t) {
  const s = String(t).toLowerCase();
  if (/skirt|brim/.test(s)) return 'skirt';
  if (/support/.test(s)) return 'support';
  if (/bridge/.test(s)) return 'bridge';
  if (/gap/.test(s)) return 'gap';
  if (/top/.test(s)) return 'top';
  if (/bottom/.test(s)) return 'bottom';
  if (/external|outer/.test(s)) return 'outer';
  if (/perimeter|inner|wall/.test(s)) return 'inner';
  if (/solid|skin/.test(s)) return 'solid';
  if (/infill|fill/.test(s)) return 'sparse';
  return 'other';
}

/**
 * Slice a manifold into G-code.
 * @returns {{ gcode, stats, layers }} layers[i] = { z, h, paths:[{type, pts}] } in bed coordinates.
 */
export function generateGcode(K, manifold, prof, { place = 'center', onProgress } = {}) {
  const p = resolveProfile(prof), w = p.lineWidthMm, FA = filArea(p.filamentDiameterMm);
  const { layers: cuts, bbox } = sliceLayers(K, manifold, p);
  const off = place === 'center' ? [p.bed.x / 2 - (bbox.min[0] + bbox.max[0]) / 2, p.bed.y / 2 - (bbox.min[1] + bbox.max[1]) / 2] : [0, 0];
  const out = [`; generated by @hyphi/slicer (preview slicer)`, `; profile ${p.name} nozzle ${p.nozzleMm} layer ${p.layerHeightMm} walls ${p.walls} infill ${p.infillPct}%`,
    `M140 S${p.bedC}`, `M104 S${p.nozzleC}`, `M190 S${p.bedC}`, `M109 S${p.nozzleC}`, p.startGcode, 'M83'];
  const stats = { layers: cuts.length, timeS: 0, filamentMm: 0, lengthByType: {}, lostAreaMm2: 0, fitsBed: true, bbox };
  const ext = bbox.max.map((v, i) => v - bbox.min[i]);
  if (ext[0] > p.bed.x || ext[1] > p.bed.y) stats.fitsBed = false;
  let pos = null, retracted = false; const layers = [];
  const move = (x, y, z, feed, e) => out.push(`G1 X${f(x)} Y${f(y)}${z != null ? ` Z${f(z)}` : ''}${e != null ? ` E${f(e, 5)}` : ''} F${Math.round(feed * 60)}`);
  const travel = (pt, z) => {
    if (pos && Math.hypot(pt[0] - pos[0], pt[1] - pos[1]) > 1.5 && !retracted && p.retractMm > 0) { out.push(`G1 E${-p.retractMm} F${p.retractSpeed * 60}`); retracted = true; }
    move(pt[0], pt[1], z, p.speed.travel);
    if (pos) stats.timeS += Math.hypot(pt[0] - pos[0], pt[1] - pos[1]) / p.speed.travel;
    pos = pt;
  };
  // skirt around the first layer
  const skirt = [];
  if (p.skirtLoops > 0 && cuts.length) {
    for (let k = 0; k < p.skirtLoops; k++) {
      const ring = cuts[0].cs.offset(p.skirtDistanceMm + k * w, 'Round', 2, 16);
      if (!ring.isEmpty()) ring.toPolygons().forEach(pg => skirt.push({ type: 'skirt', pts: [...pg, pg[0]] }));
    }
  }
  cuts.forEach((L, i) => {
    onProgress?.(i / cuts.length);
    const { paths, lostAreaMm2 } = planLayer(K, cuts, i, p);
    const all = i === 0 ? [...skirt, ...paths] : paths;
    stats.lostAreaMm2 += lostAreaMm2 * L.h;     // volume (mm³) of section narrower than one line
    out.push(`;LAYER_CHANGE`, `;Z:${f(L.z)}`, `;HEIGHT:${f(L.h)}`);
    if (i === 1) out.push(`M106 S${Math.round(p.fanPct * 2.55)}`);
    out.push(`G1 Z${f(L.z)} F${p.speed.travel * 60}`);
    const placed = [];
    let lastType = null;
    for (const path of all) {
      const pts = path.pts.map(q => [q[0] + off[0], q[1] + off[1]]); placed.push({ type: path.type, pts });
      if (path.type !== lastType) { out.push(`;TYPE:${TYPE_LABEL[path.type]}`); lastType = path.type; }
      travel(pts[0]);
      if (retracted) { out.push(`G1 E${p.retractMm} F${p.retractSpeed * 60}`); retracted = false; }
      const feed = i === 0 ? p.speed.first : ({ outer: p.speed.outerWall, inner: p.speed.innerWall, solid: p.speed.solid, sparse: p.speed.infill, skirt: p.speed.first })[path.type];
      for (let k = 1; k < pts.length; k++) {
        const len = Math.hypot(pts[k][0] - pts[k - 1][0], pts[k][1] - pts[k - 1][1]);
        const e = (len * lineArea(w, L.h) * p.flowMultiplier) / FA;
        move(pts[k][0], pts[k][1], null, feed, e);
        stats.filamentMm += e; stats.timeS += len / feed; stats.lengthByType[path.type] = (stats.lengthByType[path.type] || 0) + len;
        pos = pts[k];
      }
    }
    layers.push({ z: L.z, h: L.h, paths: placed });
  });
  out.push(p.endGcode);
  return { gcode: out.join('\n') + '\n', stats, layers };
}

/**
 * Parse G-code into layers of moves.
 * @returns {{ layers: { z, h, moves: {type,x0,y0,x1,y1,e,f,extrude}[] }[], retractions, warnings }}
 */
export function parseGcode(text, { filamentDiameterMm = 1.75 } = {}) {
  const warnings = [];
  const pos = { x: 0, y: 0, z: 0, e: 0 }; let relE = false, absXYZ = true, feed = 1500, type = 'other', retractions = 0;
  const layers = []; let cur = null, lastZ = 0;
  const layerFor = z => {
    if (!cur || Math.abs(cur.z - z) > 1e-4) { cur = { z, h: z - lastZ, moves: [] }; layers.push(cur); lastZ = z; }
    return cur;
  };
  for (const raw of text.split(/\r?\n/)) {
    const semi = raw.indexOf(';'), code = (semi >= 0 ? raw.slice(0, semi) : raw).trim(), comment = semi >= 0 ? raw.slice(semi + 1).trim() : '';
    if (comment && /^(TYPE|FEATURE)\s*:/i.test(comment)) type = normalizeType(comment.replace(/^[A-Z]+\s*:/i, ''));
    if (!code) continue;
    const [cmd, ...args] = code.split(/\s+/), v = {};
    for (const a of args) if (/^[A-Za-z]/.test(a)) v[a[0].toUpperCase()] = parseFloat(a.slice(1));
    switch (cmd.toUpperCase()) {
      case 'M82': relE = false; break;
      case 'M83': relE = true; break;
      case 'G90': absXYZ = true; break;
      case 'G91': absXYZ = false; break;
      case 'G92': if ('E' in v) pos.e = v.E; break;
      case 'G0': case 'G1': {
        if (!absXYZ) { warnings.push('relative XYZ moves are not tracked'); break; }
        const nx = v.X ?? pos.x, ny = v.Y ?? pos.y, nz = v.Z ?? pos.z;
        const de = 'E' in v ? (relE ? v.E : v.E - pos.e) : 0;
        if ('F' in v) feed = v.F;
        const xy = nx !== pos.x || ny !== pos.y;
        if (de < -1e-9) retractions++;
        if (xy) {
          const extrude = de > 1e-9;
          if (extrude) layerFor(nz).moves.push({ type, x0: pos.x, y0: pos.y, x1: nx, y1: ny, e: de, f: feed, extrude });
          else (cur ?? layerFor(nz)).moves.push({ type: 'travel', x0: pos.x, y0: pos.y, x1: nx, y1: ny, e: 0, f: feed, extrude: false });
        }
        pos.x = nx; pos.y = ny; pos.z = nz; if ('E' in v) pos.e = relE ? pos.e + v.E : v.E;
        break;
      }
      default: break;
    }
  }
  void filamentDiameterMm;
  return { layers: layers.filter(l => l.moves.length), retractions, warnings: [...new Set(warnings)] };
}

/**
 * Check G-code from any slicer: per-feature extrusion widths, time, filament, and signs that the nozzle is
 * wrong for the part (many lines far narrower than the nozzle, or a lot of tiny moves).
 */
export function analyzeGcode(parsed, { nozzleMm = 0.4, filamentDiameterMm = 1.75 } = {}) {
  const FA = filArea(filamentDiameterMm), by = {}, issues = [];
  let timeS = 0, filamentMm = 0, travelMm = 0, tiny = 0, extrudeMoves = 0, narrow = 0, wide = 0;
  for (const L of parsed.layers) for (const m of L.moves) {
    const len = Math.hypot(m.x1 - m.x0, m.y1 - m.y0), t = len / (m.f / 60 || 1);
    timeS += t;
    if (!m.extrude) { travelMm += len; continue; }
    extrudeMoves++; filamentMm += m.e;
    const h = L.h > 0 ? L.h : 0.2, wd = widthFromArea((m.e * FA) / Math.max(len, 1e-6), h);
    const b = (by[m.type] ||= { lengthMm: 0, filamentMm: 0, timeS: 0, widths: [], moves: 0 });
    b.lengthMm += len; b.filamentMm += m.e; b.timeS += t; b.moves++;
    if (len > 0.3) b.widths.push(wd);          // very short moves give noisy widths
    if (len < nozzleMm) tiny++;
    if (len > 0.3 && wd < 0.6 * nozzleMm) narrow++;
    if (len > 0.3 && wd > 2 * nozzleMm) wide++;
  }
  const features = {};
  for (const [k, b] of Object.entries(by)) {
    const ws = b.widths.sort((a, c) => a - c), q = x => (ws.length ? ws[Math.min(ws.length - 1, Math.floor(x * ws.length))] : null);
    features[k] = { label: TYPE_LABEL[k] || k, lengthMm: f(b.lengthMm, 1), filamentMm: f(b.filamentMm, 1), timeS: f(b.timeS, 1), moves: b.moves, widthMedianMm: q(0.5) && f(q(0.5)), widthP5Mm: q(0.05) && f(q(0.05)), widthP95Mm: q(0.95) && f(q(0.95)) };
  }
  const narrowPct = extrudeMoves ? (100 * narrow) / extrudeMoves : 0, tinyPct = extrudeMoves ? (100 * tiny) / extrudeMoves : 0;
  if (narrowPct > 3) issues.push({ level: 'warning', code: 'narrowLines', message: `${narrowPct.toFixed(1)}% of extrusion moves are under 60% of the ${nozzleMm} mm nozzle width — fine detail or gap fill; check it prints, or try a smaller nozzle` });
  if (tinyPct > 15) issues.push({ level: 'warning', code: 'tinyMoves', message: `${tinyPct.toFixed(0)}% of extrusion moves are shorter than the nozzle diameter — the printer may not reach the set speed or render them` });
  if (wide > 0 && (100 * wide) / Math.max(1, extrudeMoves) > 5) issues.push({ level: 'info', code: 'wideLines', message: 'many lines are over twice the nozzle width — a larger nozzle or taller layers would print this faster' });
  return { layers: parsed.layers.length, timeS: f(timeS, 0), filamentMm: f(filamentMm, 1), filamentCm3: f((filamentMm * FA) / 1000, 2), travelMm: f(travelMm, 0), retractions: parsed.retractions, features, narrowPct: f(narrowPct, 1), tinyPct: f(tinyPct, 1), issues };
}

export const TYPE_KEYS = Object.freeze(Object.keys(TYPE_LABEL));

/**
 * Flat ribbons (one quad per extrusion move, true width, at the layer's mid-height) for drawing G-code.
 * Moves are in layer order, so drawing the first `layerIndexEnd[k]` indices shows layers 0..k.
 * @returns {{ positions: Float32Array, typeIdx: Uint8Array, widthMm: Float32Array, indices: Uint32Array, layerIndexEnd: Uint32Array, layerZ: number[], bbox }}
 */
export function buildRibbons(parsed, { filamentDiameterMm = 1.75 } = {}) {
  const FA = filArea(filamentDiameterMm);
  let n = 0; for (const L of parsed.layers) for (const m of L.moves) if (m.extrude) n++;
  const positions = new Float32Array(n * 12), typeIdx = new Uint8Array(n * 4), widthMm = new Float32Array(n * 4), indices = new Uint32Array(n * 6), layerIndexEnd = new Uint32Array(parsed.layers.length), layerZ = [];
  const bb = { min: [Infinity, Infinity, Infinity], max: [-Infinity, -Infinity, -Infinity] };
  let q = 0;
  parsed.layers.forEach((L, li) => {
    layerZ.push(L.z);
    const h = L.h > 0 ? L.h : 0.2;
    for (const m of L.moves) {
      if (!m.extrude) continue;
      const dx = m.x1 - m.x0, dy = m.y1 - m.y0, len = Math.hypot(dx, dy); if (len < 1e-6) continue;
      const w = Math.min(Math.max(widthFromArea((m.e * FA) / len, h), 0.05), 3), nx = (-dy / len) * (w / 2), ny = (dx / len) * (w / 2), z = L.z - h / 2, t = TYPE_KEYS.indexOf(m.type);
      const v = q * 4;
      positions.set([m.x0 + nx, m.y0 + ny, z, m.x0 - nx, m.y0 - ny, z, m.x1 - nx, m.y1 - ny, z, m.x1 + nx, m.y1 + ny, z], q * 12);
      for (let k = 0; k < 4; k++) { typeIdx[v + k] = t < 0 ? TYPE_KEYS.indexOf('other') : t; widthMm[v + k] = w; }
      indices.set([v, v + 1, v + 2, v, v + 2, v + 3], q * 6);
      for (const [x, y] of [[m.x0, m.y0], [m.x1, m.y1]]) { bb.min[0] = Math.min(bb.min[0], x); bb.max[0] = Math.max(bb.max[0], x); bb.min[1] = Math.min(bb.min[1], y); bb.max[1] = Math.max(bb.max[1], y); }
      bb.min[2] = Math.min(bb.min[2], z - h / 2); bb.max[2] = Math.max(bb.max[2], z + h / 2);
      q++;
    }
    layerIndexEnd[li] = q * 6;
  });
  return { positions: positions.subarray(0, q * 12), typeIdx: typeIdx.subarray(0, q * 4), widthMm: widthMm.subarray(0, q * 4), indices: indices.subarray(0, q * 6), layerIndexEnd, layerZ, bbox: bb };
}
